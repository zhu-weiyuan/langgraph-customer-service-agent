"""
RAG evaluation module — metrics for measuring retrieval quality.

Metrics:
- HitRate@K: Whether ground-truth document appears in top-K results
- Recall@K: Fraction of relevant documents retrieved in top-K
- MRR (Mean Reciprocal Rank): Average reciprocal rank of first relevant result
- Coverage: Fraction of queries that return at least one result

Usage:
    from eval.ragas_eval import RAGEvaluator
    evaluator = RAGEvaluator()
    report = evaluator.evaluate(dataset)
    print(report.to_markdown())
"""

from dataclasses import dataclass, field
from typing import List, Dict, Any


@dataclass
class QueryResult:
    query: str
    ground_truth_sources: List[str]  # Expected sources
    retrieved_sources: List[str]     # Actual retrieved sources
    retrieved_texts: List[str]       # Retrieved text content


@dataclass
class EvalReport:
    total_queries: int = 0
    hit_rate_1: float = 0.0
    hit_rate_3: float = 0.0
    recall_3: float = 0.0
    mrr: float = 0.0
    coverage: float = 0.0
    details: List[Dict[str, Any]] = field(default_factory=list)

    def to_markdown(self) -> str:
        return f"""# RAG Evaluation Report

| Metric | Score |
|--------|-------|
| Total Queries | {self.total_queries} |
| HitRate@1 | {self.hit_rate_1:.2%} |
| HitRate@3 | {self.hit_rate_3:.2%} |
| Recall@3 | {self.recall_3:.2%} |
| MRR | {self.mrr:.4f} |
| Coverage | {self.coverage:.2%} |

---
*Generated by RAG Evaluator*
"""


class RAGEvaluator:
    """Evaluate RAG retrieval quality against a benchmark dataset."""

    def evaluate(self, results: List[QueryResult]) -> EvalReport:
        """Compute evaluation metrics from query results.

        Args:
            results: List of QueryResult objects with ground truth and retrieved data

        Returns:
            EvalReport with computed metrics
        """
        if not results:
            return EvalReport()

        n = len(results)
        hits_1 = 0
        hits_3 = 0
        total_recall = 0.0
        reciprocal_ranks = []
        covered = 0

        for r in results:
            gt_set = set(r.ground_truth_sources)
            retrieved = r.retrieved_sources

            if not retrieved:
                continue

            covered += 1

            # HitRate@1
            if retrieved[0] in gt_set:
                hits_1 += 1

            # HitRate@3
            if any(src in gt_set for src in retrieved[:3]):
                hits_3 += 1

            # Recall@3
            retrieved_3 = set(retrieved[:3])
            if gt_set:
                total_recall += len(retrieved_3 & gt_set) / len(gt_set)

            # MRR
            rr = 0.0
            for rank, src in enumerate(retrieved, 1):
                if src in gt_set:
                    rr = 1.0 / rank
                    break
            reciprocal_ranks.append(rr)

        report = EvalReport(
            total_queries=n,
            hit_rate_1=hits_1 / n if n else 0,
            hit_rate_3=hits_3 / n if n else 0,
            recall_3=total_recall / n if n else 0,
            mrr=sum(reciprocal_ranks) / len(reciprocal_ranks) if reciprocal_ranks else 0,
            coverage=covered / n if n else 0,
        )
        return report


