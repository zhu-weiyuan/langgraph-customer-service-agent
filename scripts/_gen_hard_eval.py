def main() -> int:
    # 校验：id 唯一、tier 合法、golden_section 非空(拒答题除外)
    seen = set()
    for c in CASES:
        assert c["id"] not in seen, f"duplicate id: {c['id']}"
        seen.add(c["id"])
        assert c["tier"] in ("normal", "edge", "adversarial", "high"), c["id"]
        if not c["should_refuse"]:
            assert c["golden_context_ids"], f"missing gid: {c['id']}"
            assert c["golden_section"], f"missing section: {c['id']}"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for c in CASES:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")

    # self-check 报告
    from collections import Counter
    tiers = Counter(c["tier"] for c in CASES)
    n = len(CASES)
    sg = sum(1 for c in CASES if c.get("sg"))
    mh = sum(1 for c in CASES if c.get("multi_hop"))
    refuse = sum(1 for c in CASES if c["should_refuse"])
    print(f"✓ 写出 {n} 条 → {OUT}")
    print("四层配比:")
    for t, label, tgt in (("normal", "正常", 0.50), ("edge", "边缘", 0.25),
                          ("adversarial", "对抗", 0.15), ("high", "高权重", 0.10)):
        print(f"  {label:<4} {tiers[t]:>3} ({tiers[t]/n:5.1%})  目标 {tgt:.0%}")
    print(f"语义鸿沟题(sg): {sg}   多跳题(multi_hop): {mh}   拒答题(should_refuse): {refuse}")
    # 文件级 golden 覆盖
    files = Counter(g for c in CASES for g in c["golden_context_ids"])
    print(f"覆盖 KB 文件数: {len(files)} / 12")
    return 0


